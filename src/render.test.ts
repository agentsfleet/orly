import { describe, expect, test } from "bun:test";
import { resolve } from "node:path";

import { RulesModel } from "./model";
import { Renderer } from "./render";

const ROOT = resolve(import.meta.dir, "..");

// Pack sets stand in for the profiles they replaced: the renderer now takes the
// list directly, so a test names exactly the packs whose filtering it asserts.
const AGENTSFLEET_PACKS = ["universal.authoring", "language.rust", "domain.sql", "product.agentsfleet"];
const DOCS_PACKS = ["universal.authoring", "language.mdx", "domain.documentation", "domain.changelog"];
const KERNEL_PACKS = ["universal.authoring", "language.rust", "domain.sql"];
// This repository's own selection, as `.orly/orly.json` declares it — the
// root render must stay current against exactly what `orly update` writes.
const DOTFILES_PACKS = ["universal.authoring", "language.typescript", "language.javascript", "language.rust", "language.go", "language.python", "language.shell", "language.mdx", "domain.sql", "domain.http", "domain.auth", "domain.documentation", "domain.changelog", "workflow.specifications", "workflow.governance", "product.agentsfleet", "persona.indy", "workflow.skills"];
const DOTFILES_COMMANDS = { conform: [["make", "conform"]], "verify.unit": [["bun", "test", "src"]] };
const MAX_ALWAYS_ON_BYTES = 16_384;
const HARD_SAFETY_FIXTURE = "fixtures/hard-safety-0.25.0.txt";

describe("Renderer", () => {
  test("renders byte-stable text for a pack set", async () => {
    const renderer = new Renderer(await RulesModel.load(ROOT));

    expect(await renderer.renderText(AGENTSFLEET_PACKS)).toBe(await renderer.renderText(AGENTSFLEET_PACKS));
  });

  test("emits CommonMark and Markdown JSX compatible headers", async () => {
    const text = await new Renderer(await RulesModel.load(ROOT)).renderText(DOCS_PACKS);

    expect(text.startsWith("> **Generated by `orly`.**")).toBeTrue();
    expect(text).not.toContain("Ruleset digest");
  });

  test("the standards index lists only the selected packs' standards", async () => {
    const renderer = new Renderer(await RulesModel.load(ROOT));
    const rust = await renderer.renderText(AGENTSFLEET_PACKS);

    expect(rust).toContain("`standards/languages/rust.md`");
    expect(rust).toContain("`standards/domains/sql.md`");
    expect(rust).not.toContain("`standards/languages/typescript.md`");

    const typescript = await renderer.renderText(["language.typescript"]);
    expect(typescript).toContain("`standards/languages/typescript.md`");
    expect(typescript).not.toContain("`standards/languages/rust.md`");
  });

  test("the root render is current and reference-closed", async () => {
    const renderer = new Renderer(await RulesModel.load(ROOT));

    expect(await renderer.rootErrors(DOTFILES_PACKS, DOTFILES_COMMANDS)).toEqual([]);
  });

  test("an unclosed pack block fails the render", async () => {
    const source = await RulesModel.load(ROOT);
    const registry = structuredClone(source.registry);
    registry.core_documents = ["fixtures/unclosed-pack-block.md"];
    const model = new RulesModel(source.root, registry);

    expect(new Renderer(model).renderText(KERNEL_PACKS)).rejects.toThrow("unclosed orly pack block");
  });
});

// Claims the rendered rules make about the machine. Each one was false when
// this suite was written: the prose said "always" where the gate runs once,
// named a chain where one gate is the boundary, made a conditional skill
// mandatory, and credited a reporting-only criterion with enforcement. Prose
// drifting back is exactly as expensive as the first time, and none of it is
// visible to a render-determinism check.
describe("the rendered rules match the machine", () => {
  test("VERIFY distinguishes Section proof from final verification", async () => {
    const text = await new Renderer(await RulesModel.load(ROOT)).renderText(DOTFILES_PACKS, DOTFILES_COMMANDS);

    expect(text).toContain("Section checks prove the changed Dimensions");
    expect(text).toContain("the final gate runs the full declared verification set");
  });

  test("CHORE(close) names the pr gate, not the whole chain", async () => {
    const text = await new Renderer(await RulesModel.load(ROOT)).renderText(DOTFILES_PACKS, DOTFILES_COMMANDS);

    expect(text).toContain("`orly gate pr` is the command CHORE(close) runs");
    expect(text).toContain("a push is never proof that tests ran");
    expect(text).toContain("every declared `verify.*` command itself");
  });

  test("the integration skill is conditional on a real input/output boundary", async () => {
    const text = await new Renderer(await RulesModel.load(ROOT)).renderText(DOTFILES_PACKS, DOTFILES_COMMANDS);

    expect(text).toContain("when the diff crosses a module boundary with real input/output");
    expect(text).not.toContain("both before the PR, never skipped");
  });

  // persona.indy is opt-in, and five engineering clauses were hiding inside it:
  // a repository dropping the voice silently dropped symlink-edit routing,
  // dotfiles backup, vault naming, sibling-repo precedent, and the
  // read-the-reference mandate with it. A pack named for voice must cost only
  // voice when it is left out.
  test("the engineering clauses survive without the persona pack", async () => {
    const renderer = new Renderer(await RulesModel.load(ROOT));
    const withoutPersona = await renderer.renderText(DOTFILES_PACKS.filter((pack) => pack !== "persona.indy"), DOTFILES_COMMANDS);

    expect(withoutPersona).toContain("Symlinked edits land in the repository that owns the file");
    expect(withoutPersona).toContain("timestamped backup");
    expect(withoutPersona).toContain("Vault names come from the environment");
    expect(withoutPersona).toContain("Check a sibling repository");
    expect(withoutPersona).toContain("Read the reference implementation before designing");
    // What persona is actually for stays behind with it.
    expect(withoutPersona).not.toContain("Indy's reference checkouts");
    expect(withoutPersona).not.toContain("🤠 Indy");
  });

  test("rendered agents file fits sixteen kibibytes", async () => {
    const model = await RulesModel.load(ROOT);
    const text = await new Renderer(model).renderText(Object.keys(model.registry.packs as object), DOTFILES_COMMANDS);

    expect(Buffer.byteLength(text)).toBeLessThanOrEqual(MAX_ALWAYS_ON_BYTES);
  });

  test("hard safety survives verbatim", async () => {
    const model = await RulesModel.load(ROOT);
    const text = await new Renderer(model).renderText(Object.keys(model.registry.packs as object), DOTFILES_COMMANDS);
    const bullets = (await Bun.file(resolve(ROOT, HARD_SAFETY_FIXTURE)).text()).split("\n").filter(Boolean);

    expect(bullets).toHaveLength(15);
    expect(bullets.filter((bullet) => !text.includes(bullet))).toEqual([]);
  });

  test("always-on file disallows gstack learn", async () => {
    const text = await new Renderer(await RulesModel.load(ROOT)).renderText(DOTFILES_PACKS, DOTFILES_COMMANDS);

    expect(text).toContain("gstack `/learn` is not used");
  });

  test("SOUL names the blocking language criterion and its changed-prose scope", async () => {
    const soul = await Bun.file(resolve(ROOT, "SOUL.md")).text();

    expect(soul.replace(/\s+/g, " ")).toContain("`docs.language` criterion rejects mechanical language findings in changed prose");
    expect(soul).toContain("`orly gate verify` and `orly gate pr`");
    expect(soul).not.toContain("stays green");
  });
});
