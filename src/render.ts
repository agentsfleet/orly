import { lstatSync } from "node:fs";
import { join, relative } from "node:path";

import {
  isString,
  JsonObject,
  objectArray,
  objectValue,
  OrlyError,
  RulesModel,
  stringArray,
} from "./model";
import { referenceClosureErrors, renderProfileText } from "./references";
import { ruleBlocks, STANDARDS_DIRECTORY } from "./standards";

const STANDARDS_PREFIX = `${STANDARDS_DIRECTORY}/`;

const NEWLINE = "\n";
const REGISTRY_PACKS_LABEL = "registry packs";
const TABLE_SEPARATOR = "|---|---|";
const AGENTS_FILENAME = "AGENTS.md";
const TITLE_PREFIX = "# ";
const INDEX_HEADER_ROWS = 4;
const CODE_FENCE = /^\s*(?:```|~~~)/;
const HEADING = /^#{1,5} /;

// One render target: the repository root's AGENTS.md. Dispatch façades and
// docs are referenced in place — they are the sources, not copies — so the
// only generated artifact is the one file agent runtimes auto-load.
export class Renderer {
  readonly model: RulesModel;

  constructor(model: RulesModel) {
    this.model = model;
  }

  async renderText(packs: string[], commands: Record<string, string[][]> = {}, projectRoot?: string): Promise<string> {
    const sections = [
      "> **Generated by `orly`.**\n> Do not edit. Update the source rule in `core/` or the pack it names,\n> then commit — every clone reads the committed rules.",
    ];
    const { selected, known } = this.packSelection(packs);
    for (const [index, document] of stringArray(this.model.registry.core_documents, "core documents").entries()) {
      const text = renderProfileText(await Bun.file(join(this.model.root, document)).text(), selected, known, document);
      // One title per page: documents after the first nest under it.
      sections.push(index === 0 ? text : demoteHeadings(text));
    }
    sections.push(await this.standardsIndex(packs));
    sections.push(this.commandTable(commands));
    if (projectRoot) {
      const projectPath = join(projectRoot, "AGENTS.project.md");
      if (await Bun.file(projectPath).exists()) sections.push((await Bun.file(projectPath).text()).trim());
    }
    return `${sections.filter(Boolean).join("\n\n---\n\n")}\n`;
  }

  // Currency check: the committed root AGENTS.md must byte-match the render.
  async rootErrors(packs: string[], commands: Record<string, string[][]> = {}): Promise<string[]> {
    const target = join(this.model.root, AGENTS_FILENAME);
    if (!(await Bun.file(target).exists())) return [`missing generated rules: ${relative(this.model.root, target)}`];
    if (lstatSync(target).isSymbolicLink()) return [`generated rules must be a real file: ${AGENTS_FILENAME}`];
    const expected = await this.renderText(packs, commands);
    const actual = await Bun.file(target).text();
    if (expected !== actual) return [`generated rules are stale: run \`orly update\``];
    return [];
  }

  private packSelection(packs: string[]): { selected: Set<string>; known: Set<string> } {
    return { selected: new Set(packs), known: new Set(Object.keys(objectValue(this.model.registry.packs, REGISTRY_PACKS_LABEL))) };
  }

  // The index names what to read before editing. It replaces the table of
  // selected packs, which said where rules came from rather than what they are.
  private async standardsIndex(selected: string[]): Promise<string> {
    const rows = ["## Standards", "", "| Standard | Covers |", TABLE_SEPARATOR];
    for (const path of this.selectedStandards(selected)) {
      const text = await Bun.file(join(this.model.root, path)).text();
      // A template ships beside the standards but declares no rules.
      if (ruleBlocks(text).length === 0) continue;
      rows.push(`| \`${path}\` | ${standardTitle(text, path)} |`);
    }
    if (rows.length === INDEX_HEADER_ROWS) rows.push("| None | No selected pack carries a standard |");
    return rows.join(NEWLINE);
  }

  private selectedStandards(selected: string[]): string[] {
    const packs = objectValue(this.model.registry.packs, REGISTRY_PACKS_LABEL);
    const paths = new Set<string>();
    for (const name of selected) {
      const pack = objectValue(packs[name], `pack ${name}`);
      for (const file of objectArray(pack.managed_files, `pack ${name} managed_files`)) {
        if (isString(file.source) && file.source.startsWith(STANDARDS_PREFIX)) paths.add(file.source);
      }
    }
    return [...paths].sort();
  }

  private commandTable(commands: Record<string, string[][]>): string {
    const rows = ["## Repository commands", "", "| Responsibility | Commands |", TABLE_SEPARATOR];
    for (const name of Object.keys(commands).sort()) {
      const invocations = commands[name];
      if (!Array.isArray(invocations)) continue;
      const rendered = invocations.map((invocation) => Array.isArray(invocation) ? `\`${invocation.map((argument) => quoteArgument(String(argument))).join(" ")}\`` : "").join("<br>");
      rows.push(`| \`${name}\` | ${rendered} |`);
    }
    if (Object.keys(commands).length === 0) rows.push("| None | Declare them in `.orly/orly.json` |");
    return rows.join(NEWLINE);
  }
}

function demoteHeadings(text: string): string {
  let inFence = false;
  return text.split(NEWLINE).map((line) => {
    if (CODE_FENCE.test(line)) inFence = !inFence;
    return !inFence && HEADING.test(line) ? `#${line}` : line;
  }).join(NEWLINE);
}

function standardTitle(text: string, path: string): string {
  const heading = text.split(NEWLINE).find((line) => line.startsWith(TITLE_PREFIX));
  if (!heading) throw new OrlyError(`standard has no title heading: ${path}`);
  return heading.slice(TITLE_PREFIX.length).trim();
}

function quoteArgument(value: string): string {
  return /^[A-Za-z0-9_./:=+-]+$/.test(value) ? value : `'${value.replaceAll("'", `'\\''`)}'`;
}
